"""
Does latent gauge fixing close the Theta < delta gap?

The certificate reports delta = min_{i,j} inf_x |det g_ji(x)|.  Rescaling the
latent coordinates of each chart leaves epsilon, eta and the orientability
verdict untouched but moves delta (see atlasae/gauge.py).  This script trains
each atlas as in the paper, then reports delta before and after the optimal
rescaling, alongside the lower bound on the stability threshold

    Theta >= d[(3 - eta) eta]^d          (Proposition, supplement)

so that one can see whether Theta < delta becomes attainable.

Usage:
    python run_gauge.py --manifolds S2 Mobius --seeds 42 43 44 45 46
    python run_gauge.py --manifolds S2 --epochs 1000        # quick check
    python run_gauge.py --latex
"""

import argparse
import json
import os
import sys
from datetime import datetime

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))          # experiments/
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "..", "src"))


def theta_lower_bound(eta, d=2):
    return np.inf if eta >= 1 else d * ((3.0 - eta) * eta) ** d


def run_one(name, seed, epochs=None, pca_k=25, min_points=5):
    import tensorflow as tf
    from atlasae import (AtlasAutoencoder, fast_fit, pca_tangent_frames,
                         compute_eta_true_pointwise, gauge_report)
    import paper_experiments as PE

    cfg = PE.MANIFOLDS[name]
    np.random.seed(seed)
    tf.random.set_seed(seed)

    points, _ = cfg["sampler"](cfg["n"], seed, **cfg.get("sampler_kw", {}))
    assignments = cfg["cover"](points, seed)
    frames = pca_tangent_frames(points, d=2, k=pca_k)

    system = AtlasAutoencoder(data=points, n_charts=len(assignments),
                              subset_assignments=assignments,
                              latent_dim=2, hidden_dims=[32, 16])
    fast_fit(system, epochs=epochs or cfg["epochs"], batch_size=64,
             lambda_jac=cfg.get("lambda_jac", 0.0),
             lambda_diff=cfg.get("lambda_diff", 0.0), verbose=False)

    eps = max(float(system.compute_varepsilon(
        i, tf.constant(points[assignments[i]], dtype=tf.float32)).numpy())
        for i in range(system.n_charts))
    etas = [float(compute_eta_true_pointwise(
        system.autoencoders[i], points[assignments[i]],
        frames[assignments[i]]).max()) for i in range(system.n_charts)]
    eta = max(etas)

    g = gauge_report(system, min_points=min_points, d=2)
    lb = theta_lower_bound(eta)
    return dict(manifold=name, seed=seed, n_charts=int(system.n_charts),
                varepsilon=eps, eta_pca=eta,
                n_eta_outliers=int(sum(e > 1 for e in etas)),
                theta_lower_bound=float(lb),
                closes_gap_before=bool(lb < g["delta_before"]),
                closes_gap_after=bool(lb < g["delta_after"]),
                closes_gap_at_ceiling=bool(lb < g["ceiling"]),
                **{k: v for k, v in g.items() if k != "lambdas"})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifolds", nargs="+", default=["S2", "Mobius", "RP2"])
    ap.add_argument("--seeds", type=int, nargs="+", default=[42])
    ap.add_argument("--epochs", type=int, default=None)
    ap.add_argument("--min-points", type=int, default=5)
    ap.add_argument("--latex", action="store_true")
    a = ap.parse_args()

    rows = []
    for m in a.manifolds:
        for s in a.seeds:
            r = run_one(m, s, epochs=a.epochs, min_points=a.min_points)
            rows.append(r)
            print(f"\n=== {m} seed {s} ===")
            print(f"  eps={r['varepsilon']:.4f}  eta={r['eta_pca']:.3f}  "
                  f"Theta_LB={r['theta_lower_bound']:.3f}")
            print(f"  delta  before={r['delta_before']:.4f}  "
                  f"after={r['delta_after']:.4f}  "
                  f"ceiling={r['ceiling']:.4f}  (gain x{r['gain']:.1f})")
            print(f"  Theta<delta:  before={r['closes_gap_before']}  "
                  f"after={r['closes_gap_after']}  "
                  f"at ceiling={r['closes_gap_at_ceiling']}")

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    d = os.path.join(HERE, f"results_gauge_{stamp}")
    os.makedirs(d, exist_ok=True)
    json.dump(rows, open(os.path.join(d, "results.json"), "w"), indent=2)
    print(f"\nwrote {d}/results.json")

    if a.latex:
        print("\n% generated by E6_gauge/run_gauge.py")
        for r in rows:
            mark = "\\cmark" if r["closes_gap_after"] else "\\xmark"
            print(f"{r['manifold']} & {r['seed']} & {r['eta_pca']:.2f} & "
                  f"{r['delta_before']:.4f} & {r['delta_after']:.3f} & "
                  f"{r['ceiling']:.3f} & {r['theta_lower_bound']:.2f} & "
                  f"{mark} \\\\")


if __name__ == "__main__":
    main()
