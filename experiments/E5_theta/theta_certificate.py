"""
How far is the *explicit* second hypothesis of the global stability theorem from
being satisfied?

Theorem (sign-cocycle stability) requires

    eta < 1        and        Theta < delta,

    Theta   = max( d * Gamma * (L_E L_D + Gamma)^(d-1),  K_det )
    Gamma   = L_E * eta_eff * L_D + L_E' * eps_t * (1 + eta_eff) * L_D
    eta_eff = (L_E L_D + 2) eta / (1 - eta) + L_Phi' * eps

The pipeline reported in the paper checks eta_pca < 1, eps <= eps*, delta > delta*.
It does NOT check Theta < delta, because Theta involves the four regularity
constants L_E, L_E', L_D, L_D'.

It turns out that Theta can be bounded below *without measuring any of them*.

    Lemma.  For an (eps,eta)-approximate atlas with eta < 1,
                P := L_E L_D  >=  1 - eta.
    Proof.  For x in U_i and a unit v in T_xM,
            ||d(Phi_i)_x v|| >= ||v|| - ||(d(Phi_i)_x - Id)v|| >= 1 - eta,
            so sigma_max(d(Phi_i)_x|_T) >= 1 - eta.  On the other hand
            d(Phi_i)_x = d(D_i) d(E_i), so sigma_max <= L_D L_E.

    Corollary.  Dropping the non-negative terms L_Phi' eps and
    L_E' eps_t (1 + eta_eff) L_D, and using that s -> s(s+2) is increasing,

        Gamma >= P (P + 2) eta / (1 - eta) >= (3 - eta) eta,
        Theta >= d * Gamma * (L_E L_D + Gamma)^(d-1) >= d * Gamma^d
              >= d * [ (3 - eta) eta ]^d  =:  Theta_LB(eta, d).

Theta_LB depends only on the measured eta and the intrinsic dimension, so it can
be evaluated for every run in the paper.  This script does that.

Usage:
    python theta_certificate.py            # console table
    python theta_certificate.py --latex    # LaTeX rows
"""

import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))  # experiments/

import make_master_table as M


def theta_lower_bound(eta, d=2):
    """d * [(3 - eta) eta]^d, valid whenever eta < 1 (else the theorem is void)."""
    if eta >= 1:
        return np.inf
    return d * ((3.0 - eta) * eta) ** d


def eta_max_for(delta, d=2):
    """Largest eta for which Theta_LB(eta,d) < delta can hold."""
    from scipy.optimize import brentq
    if theta_lower_bound(1e-9, d) >= delta:
        return 0.0
    try:
        return brentq(lambda e: theta_lower_bound(e, d) - delta, 1e-9, 0.999999)
    except ValueError:
        return 0.999999


def rows(d=2):
    out = []
    for name, pattern, truth in M.SOURCES:
        recs, path = M.load(pattern)
        if recs is None:
            continue
        eta = float(np.mean([r["eta_pca"] for r in recs]))
        delta = float(np.mean([r["delta"] for r in recs]))
        d_run = int(recs[0].get("d", d))   # records carry their own dimension
        lb = theta_lower_bound(eta, d_run)
        out.append(dict(name=name, n=len(recs), eta=eta, delta=delta,
                        theta_lb=lb, ratio=(lb / delta if delta > 0 else np.inf),
                        satisfied=bool(lb < delta)))
    return out


def main(latex=False, d=2):
    rr = rows(d)
    if latex:
        print("% generated by E5_theta/theta_certificate.py")
        for r in rr:
            lb = "$\\infty$" if not np.isfinite(r["theta_lb"]) else f"{r['theta_lb']:.2f}"
            ra = "$\\infty$" if not np.isfinite(r["ratio"]) else f"{r['ratio']:.0f}"
            print(f"{r['name']} & {r['eta']:.2f} & {r['delta']:.3f} & {lb} & {ra} "
                  f"& \\xmark \\\\")
        return

    print(f"\nLower bound  Theta >= d[(3-eta)eta]^d   (d={d}); the theorem needs "
          f"Theta < delta.\n")
    hdr = (f"{'experiment':28} {'runs':>4} {'eta_pca':>8} {'delta':>8} "
           f"{'Theta_LB':>9} {'ratio':>8}  Theta<delta?")
    print(hdr); print("-" * len(hdr))
    for r in rr:
        plain = (r["name"].replace("$", "").replace('\\"o', "o")
                 .replace("\\R", "R").replace("\\mathbb{R}P^2", "RP2"))
        lb = "inf" if not np.isfinite(r["theta_lb"]) else f"{r['theta_lb']:.3f}"
        ra = "inf" if not np.isfinite(r["ratio"]) else f"{r['ratio']:.1f}"
        print(f"{plain:28} {r['n']:>4} {r['eta']:8.3f} {r['delta']:8.4f} "
              f"{lb:>9} {ra:>8}  {'YES' if r['satisfied'] else 'no'}")

    # best individual trial
    best = None
    for name, pattern, truth in M.SOURCES:
        recs, _ = M.load(pattern)
        if recs is None:
            continue
        for r in recs:
            if r["delta"] <= 0:
                continue
            ratio = theta_lower_bound(r["eta_pca"], int(r.get("d", d))) / r["delta"]
            if best is None or ratio < best[0]:
                best = (ratio, name, r.get("seed"), r["eta_pca"], r["delta"])
    print(f"\nbest single trial: Theta_LB/delta = {best[0]:.2f} "
          f"({best[1].replace('$','')}, seed {best[2]}, eta={best[3]:.3f}, "
          f"delta={best[4]:.4f})")
    print(f"\nEven with delta = 1 (near-isometric transitions, the most "
          f"favourable case),\nTheta_LB < delta requires eta < "
          f"{eta_max_for(1.0, d):.3f}.")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    ap.add_argument("-d", type=int, default=2)
    a = ap.parse_args()
    main(latex=a.latex, d=a.d)
